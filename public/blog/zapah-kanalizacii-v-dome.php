        <h1>Запах канализации в доме и способы его устранения</h1>
        <div class="post-img post-10"></div>
        <div class="post-text">
           <p>
	           Внутри любой канализационной системы, в которую сливается серый сток, всегда образуется неприятный запах. 
              Ввиду некоторых причин, этот запах может выйти наружу. 
              Часто причиной его появления считают неправильную работу станции биологической очистки сточных вод, но это ошибка, 
              если станция не стоит рядом с домом под открытыми окнами. 
              На самом деле, запах появляется из-за разгерметизации системы. Для его устранения необходимо проверить следующее:
           </p>
           <h2>1. Гидрозатворы</h2>
           <p>
               Из-за долгого отсутствия гидрозатвор может высохнуть и начать пропускать запах. 
               Для устранения неполадки достаточно налить воды. 
               Сифон под раковиной может быть неправильно собран, необходимо его проверить.
            </p>
            <h2>2. Резиновая манжета</h2>
            <p>
               Водоотводящий шланг от стиральной или посудомоечной машины обычно вставляется в раструб канализационной трубы через резиновую манжету. 
               Необходимо убедиться, что соединение плотное.
            </p>
            <h2>3. Воздушный клапан</h2>
            <p>
               Некоторые системы оснащены воздушным клапаном. 
               Он может выйти из строя и начать пропускать воздух из канализации. 
               В этом случае требуется его замена.
            </p>
            <h2>4. Неправильная установка унитаза</h2>
            <p>
               Многие сантехники вставляют гибкую гофру для унитаза прямо в раструб трубы 110. 
               Это ошибка, потому что гофра должна вставляться в саму трубу, т. к. диаметр раструба шире. 
               Чтобы устранить запах, необходимо сначала вставить обрезок трубы 110 в раструб, а затем уже в него ввести гибкую гофру.
            </p>
            
            <p>
               Основные причины запаха канализации в доме — это неисправность гидрозатворов либо неправильный монтаж. 
            </p>
