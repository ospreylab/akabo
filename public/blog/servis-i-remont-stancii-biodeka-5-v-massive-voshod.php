        <div class="post-text">
           <p>
	           У клиента из массива Восход Синявского городского поселения Кировского района Ленинградской области на станции биологической очистки загорелась аварийная лампа. 
              Было принято решение выявить причину возникновения неисправности и заодно сделать очередное сервисное обслуживание, чтобы сэкономить деньги заказчика.
           </p>
           <h2>1. Визуальный осмотр</h2>
           <p>
               В результате осмотра стало понятно, что в станции сгорел насос принудительной откачки очищенной воды. 
               Это привело к затоплению станции. 
               К счастью вода не добралась до компрессорного отсека.
            </p>
            <h2>2. Замена насоса</h2>
            <p>
               Насос для замены всегда есть в наличии. Удалили старый насос и поставили новый. 
               Зафиксировали поплавок на нужной высоте и проверили на корректность срабатывания. 
               Из-за неправильной фиксации поплавка может возникнуть проблема с включением и выключением насоса.
            </p>
            <h2>3. Промывка фильтра компрессора</h2>
            <p>
               Фильтр был сильно загрязнен. 
               Промыли проточной водой и повесили сушиться на солнце.
            </p>
            <h2>4. Откачка</h2>
            <p>
               Из камеры вторичного отстойника откачали воду, затем откачали жидкость из камеры стабилизатора ила.
            </p>
            <h2>5. Промывка компонентов и станции</h2>
            <p>
               Демонтировали главный эрлифт, разобрали на компоненты и промыли мойкой высокого давления. 
               В дегазатор вставили шланг и пустили напор воды, чтобы очистить его от твердых осадков. 
               Промыли эрлифт рециркуляции, очистили стенки от следов ила.
            </p>
            <h2>6. Обратное заполнение</h2>
             <p>
               Заполнили камеры чистой водой до нужного уровня.
            </p>
             <h2>7. Удаление мусора</h2>
             <p>
               С приемной камеры и с камеры аэротенка выловили крупные фракции не разлагаемых остатков.
            </p>
            <h2>8. Сборка</h2>
            <p>
               Установили все оборудование назад. В компрессор установили очищенный фильтр.
            </p>
            <h2>9. Запуск</h2>
            <p>
               Включили электроприборы в сеть и убедились, что все работает корректно. 
               Несколько раз проверили насос принудительного выброса на предмет включения и выключения по поплавку.
            </p>
            <p>
               Заказчику после проведения сервиса были даны рекомендации по дальнейшей эксплуатации. 
               Обратили внимание, что фильтр компрессора необходимо очищать самостоятельно хотя бы раз в три месяца.
            </p>
